BACKEND_ID = "python-http-reference"
BACKEND_VERSION = "1.0.0"
COMPILER_VERSION = "mozaic-collector-engineering/0.3.0"
PROFILE = json.loads(
    files("collector_engineering")
    .joinpath("profiles/python-http-reference-v1.json")
    .read_text(encoding="utf-8")
)
BACKEND_CAPABILITIES = frozenset(PROFILE["capabilities"])


def _platform_slug() -> str:
    system = platform.system().lower()
    machine = {"x86_64": "amd64", "aarch64": "arm64"}.get(
        platform.machine().lower(), platform.machine().lower()
    )
    return f"{system}/{machine}"


def check_capabilities(ir: TypedIR) -> list[dict[str, str]]:
    missing = sorted(set(ir.document["capabilities"]) - BACKEND_CAPABILITIES)
    return [
        {
            "code": "CAPABILITY_UNSUPPORTED",
            "capability": name,
            "backend": BACKEND_ID,
            "message": f"backend {BACKEND_ID} does not support {name}",
        }
        for name in missing
    ]


def generate_python(
    ir: TypedIR,
    *,
    fixture_identities: list[dict[str, Any]] | None = None,
    runtime_identity: dict[str, Any] | None = None,
) -> bytes:
    if runtime_identity is None:
        _, runtime_identity = runtime_bundle_files(
            ("reference_runtime.py", "syntax.py")
        )
    variables = {
        node["operation_id"]: f"v_{index}"
        for index, node in enumerate(ir.document["nodes"])
    }
    lines = [
        '"""Generated by Collector Engineering. Offline fixture execution only."""',
        "import argparse",
        "import json",
        "import sys",
        "from pathlib import Path",
        "sys.path.insert(0, str(Path(__file__).resolve().parent / 'runtime'))",
        "from mozaic_bot_runtime import reference_runtime",
        "from mozaic_bot_runtime.identity import verify as verify_runtime",
        "RUNTIME_ROOT = (Path(__file__).resolve().parent / 'runtime' / 'mozaic_bot_runtime').resolve(strict=True)",
        "if Path(reference_runtime.__file__).resolve().parent != RUNTIME_ROOT:",
        "    raise RuntimeError('[BUILD_RUNTIME_IMPORT_MISMATCH] reference runtime was not imported from this BotBuild')",
        f"RUNTIME_IDENTITY = {runtime_identity!r}",
        "verify_runtime(RUNTIME_ROOT, RUNTIME_IDENTITY['files'], RUNTIME_IDENTITY['sha256'])",
        "RuntimeContext = reference_runtime.RuntimeContext",
        "RuntimeFailure = reference_runtime.RuntimeFailure",
        "fetch_fixture = reference_runtime.fetch_fixture",
        "discover_links = reference_runtime.discover_links",
        "paginate = reference_runtime.paginate",
        "select_html_records = reference_runtime.select_html_records",
        "select_json_records = reference_runtime.select_json_records",
        "extract_fields = reference_runtime.extract_fields",
        "write_records = reference_runtime.write_records",
        "write_raw_references = reference_runtime.write_raw_references",
        "write_report = reference_runtime.write_report",
        "",
        "SOURCE = " + repr(ir.document["source"]),
        "BUDGETS = " + repr(ir.document["budgets"]),
        "EXPECTED_FIXTURES = " + repr(fixture_identities or []),
        "IR_VERSION = " + repr(ir.document["ir_version"]),
        "",
        "def run(fixture_root: str, output_root: str):",
        "    ctx = RuntimeContext.create(fixture_root, output_root, SOURCE, BUDGETS, EXPECTED_FIXTURES)",
    ]
    for node in ir.document["nodes"]:
        op = f"{node['operator_type']}/{node['operator_version']}"
        args = node["inputs"]
        variable = variables[node["operation_id"]]
        if op == "http.fetch/v1":
            code = f"fetch_fixture(ctx, url={args['url']!r}, content_type={args['content_type']!r}, evidence_refs={args['evidence_refs']!r})"
        elif op == "links.discover/v1":
            binding = args["document"]
            code = f"discover_links(ctx, {variables[binding['operation']]}, selector={args['selector']!r}, max_links={args['max_links']!r}, evidence_refs={args['evidence_refs']!r})"
        elif op == "pagination.bounded/v1":
            binding = args["links"]
            code = f"paginate(ctx, {variables[binding['operation']]}, max_pages={args['max_pages']!r})"
        elif op == "select.html_records/v1":
            binding = args["documents"]
            code = f"select_html_records(ctx, {variables[binding['operation']]}, selector={args['selector']!r}, cardinality={args['cardinality']!r}, max_matches={args['max_matches']!r}, evidence_refs={args['evidence_refs']!r})"
        elif op == "select.json_records/v1":
            binding = args["document"]
            code = f"select_json_records(ctx, {variables[binding['operation']]}, array_path={args['array_path']!r}, max_matches={args['max_matches']!r}, evidence_refs={args['evidence_refs']!r})"
        elif op == "extract.fields/v1":
            binding = args["records"]
            code = f"extract_fields(ctx, {variables[binding['operation']]}, fields={args['fields']!r}, operation_id={node['operation_id']!r})"
        elif op == "output.records/v1":
            binding = args["records"]
            code = f"write_records(ctx, {variables[binding['operation']]})"
        elif op == "output.raw/v1":
            binding = args["documents"]
            code = f"write_raw_references(ctx, {variables[binding['operation']]})"
        else:
            raise PlaybookError(f"[CAPABILITY_UNSUPPORTED] cannot generate {op}")
        lines.append(f"    {variable} = {code}")
    output_nodes = [
        node
        for node in ir.document["nodes"]
        if node["operator_type"] == "output.records"
    ]
    if not output_nodes:
        raise PlaybookError("[OUTPUT_PIPELINE_INCOMPLETE] no output.records operation")
    lines.extend(
        [
            f"    write_report(ctx, {variables[output_nodes[-1]['operation_id']]})",
            f"    return {variables[output_nodes[-1]['operation_id']]}",
            "",
            "def main(argv=None):",
            "    parser = argparse.ArgumentParser()",
            "    parser.add_argument('--fixtures', required=True)",
            "    parser.add_argument('--output', required=True)",
            "    args = parser.parse_args(argv)",
            "    try:",
            "        report = run(args.fixtures, args.output)",
            "    except RuntimeFailure as error:",
            "        print(str(error))",
            "        return 1",
            "    print(json.dumps(report, sort_keys=True))",
            "    return 0",
            "",
            "if __name__ == '__main__':",
            "    raise SystemExit(main())",
            "",
        ]
    )
    return "\n".join(lines).encode("utf-8")


def _safe_output_path(output: Path) -> Path:
    if ".." in output.parts:
        raise PlaybookError("[BUILD_PATH_UNSAFE] output path traversal is not allowed")
    absolute = output.absolute()
    current = Path(absolute.anchor)
    for part in absolute.parts[1:]:
        current /= part
        if current.exists() and current.is_symlink():
            raise PlaybookError("[BUILD_PATH_UNSAFE] output path contains a symlink")
    if absolute.exists():
        raise PlaybookError(
            "[BUILD_ALREADY_EXISTS] refusing to overwrite a build directory"
        )
    missing_parents = []
    parent = absolute.parent
    while not parent.exists():
        missing_parents.append(parent)
        parent = parent.parent
    for missing in reversed(missing_parents):
        try:
            missing.mkdir(mode=0o700)
        except FileExistsError:
            if missing.is_symlink() or not missing.is_dir():
                raise PlaybookError(
                    "[BUILD_PATH_UNSAFE] output parent is not a real directory"
                )
    current = Path(absolute.anchor)
    for part in absolute.parts[1:-1]:
        current /= part
        if current.is_symlink() or not current.is_dir():
            raise PlaybookError("[BUILD_PATH_UNSAFE] output parent is unsafe")
    return absolute


def compile_build(
    parsed: ParsedPlaybook,
    *,
    fixture_root: Path,
    output: Path,
    lockfile: Path,
    playbook_sha256: str | None = None,
    target_platform: str | None = None,
) -> dict[str, Any]:
    result = validate_playbook_v2(parsed, fixture_root=fixture_root)
    if not result.valid:
        details = "; ".join(
            f"{item.code} {item.path}: {item.message}" for item in result.diagnostics
        )
        raise PlaybookError(details)
    ir = build_typed_ir(parsed, fixture_root=fixture_root)
    failures = check_capabilities(ir)
    if failures:
        raise PlaybookError(
            "; ".join(
                f"{item['code']} {item['capability']}: {item['message']}"
                for item in failures
            )
        )
    # Capability rejection happens before the output directory is created.
    destination = _safe_output_path(output)
    lock_digest = hashlib.sha256(lockfile.read_bytes()).hexdigest()
    if playbook_sha256 is not None and (
        not isinstance(playbook_sha256, str)
        or len(playbook_sha256) != 64
        or any(char not in "0123456789abcdef" for char in playbook_sha256)
    ):
        raise PlaybookError(
            "[PLAYBOOK_DIGEST_INVALID] playbook digest must be lowercase sha256"
        )
    target_platform = target_platform or _platform_slug()
    if (
        not isinstance(target_platform, str)
        or "/" not in target_platform
        or any(
            not part or not part.replace("-", "").replace("_", "").isalnum()
            for part in target_platform.split("/", 1)
        )
    ):
        raise PlaybookError("[TARGET_PLATFORM_INVALID] target platform is invalid")
    fixture_index = json.loads(
        (fixture_root / "index.json").read_text(encoding="utf-8")
    )
    evidence_refs = {item["evidence_ref"] for item in parsed.document["evidence"]}
    fixtures = sorted(
        [
            {
                "url": page["url"],
                "evidence_ref": page["evidence_ref"],
                "sha256": page["sha256"],
                "size_bytes": (fixture_root / page["body_file"]).stat().st_size,
                "content_type": page["content_type"],
                "status": page["status"],
                "source_id": fixture_index["source"]["source_id"],
                "source_revision": fixture_index["source"]["revision"],
            }
            for page in fixture_index["pages"]
            if page.get("evidence_ref") in evidence_refs
        ],
        key=lambda item: (item["url"], item["evidence_ref"]),
    )
    runtime_files, runtime_identity = runtime_bundle_files(
        ("reference_runtime.py", "syntax.py")
    )
    source = generate_python(
        ir, fixture_identities=fixtures, runtime_identity=runtime_identity
    )
    files = {
        "bot.py": source,
        "config/offline.json": canonical_json(
            {
                "network": "disabled",
                "fixture_index": "index.json",
                "output_format": "jsonl",
            }
        ),
        "runtime-reference.json": canonical_json(
            {
                "package": "mozaic-collector-engineering",
                "runtime": RUNTIME_VERSION,
                "required_dependency": "selectolax==0.4.13",
            }
        ),
        "README.md": (
            b"# Generated offline bot\n\n"
            b"This build reads verified local fixtures only. It does not open network connections.\n\n"
            b"Run from the monorepo environment:\n\n"
            b"```sh\n"
            b"uv run --locked --package mozaic-collector-engineering python bot.py --fixtures PATH --output PATH\n"
            b"```\n\n"
            b"Outputs are `records.jsonl` and `report.json`. Decimal fields are JSON strings in canonical base-10 form.\n"
        ),
    }
    files.update(runtime_files)
    generated = {
        name: hashlib.sha256(data).hexdigest() for name, data in sorted(files.items())
    }
    manifest_core = {
        "manifest_version": "bot-build-manifest/v2",
        "playbook_id": parsed.document["playbook_id"],
        "bot_id": derive_bot_id(
            parsed.document["playbook_id"], parsed.document["source"]["source_id"]
        ),
        "source": {
            "source_id": parsed.document["source"]["source_id"],
            "source_revision": parsed.document["source"]["revision"],
        },
        "playbook_version": parsed.document["dsl_version"],
        "playbook_sha256": playbook_sha256,
        "ir_version": IR_VERSION,
        "ir_sha256": ir.sha256,
        "backend_id": BACKEND_ID,
        "backend_version": BACKEND_VERSION,
        "capability_profile_sha256": hashlib.sha256(
            canonical_json(PROFILE)
        ).hexdigest(),
        "compiler_version": COMPILER_VERSION,
        "runtime_identity": runtime_identity,
        "capability_profile_id": "python-http-reference-v1",
        "dependency_identity": {
            "lockfile_sha256": lock_digest,
            "packages": {"selectolax": "0.4.13"},
        },
        "compatibility": {
            "worker_contract": "python-reference/v1",
            "execution_mode": "fixture-only",
            "python_minor": f"{platform.python_version_tuple()[0]}.{platform.python_version_tuple()[1]}",
            "target_platform": target_platform,
        },
        "toolchain": {
            "python": platform.python_version(),
            "python_implementation": platform.python_implementation(),
            "platform_system": platform.system(),
            "platform_machine": platform.machine(),
            "runtime": RUNTIME_VERSION,
            "selectolax": "0.4.13",
        },
        "dependency_lock_sha256": lock_digest,
        "generated_files": generated,
        "input_fixtures": fixtures,
    }
    manifest = {
        **manifest_core,
        "build_id": hashlib.sha256(canonical_json(manifest_core)).hexdigest(),
    }
    destination.mkdir(parents=True, mode=0o700)
    try:
        for name, data in files.items():
            target = destination / name
            target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
            if target.is_symlink() or ".." in Path(name).parts:
                raise PlaybookError("[BUILD_PATH_UNSAFE] generated file path is unsafe")
            with target.open("xb") as stream:
                stream.write(data)
        with (destination / "manifest.json").open("xb") as stream:
            stream.write(
                json.dumps(manifest, sort_keys=True, indent=2).encode() + b"\n"
            )
    except BaseException:
        shutil.rmtree(destination)
        raise
    return manifest


def verify_build(
    directory: Path,
    *,
    expected_backend_id: str = BACKEND_ID,
    expected_backend_version: str = BACKEND_VERSION,
    expected_compiler_version: str = COMPILER_VERSION,
    profile: dict[str, Any] = PROFILE,
    expected_toolchain: dict[str, str] | None = None,
) -> dict[str, Any]:
    manifest_path = directory / "manifest.json"
    try:
        manifest_bytes = manifest_path.read_bytes()
        manifest = json.loads(manifest_bytes)
        if (
            isinstance(manifest, dict)
            and manifest.get("manifest_version") == "bot-build-manifest/v2"
        ):
            if (
                manifest.get("backend_id") != expected_backend_id
                or manifest.get("backend_version") != expected_backend_version
                or manifest.get("compiler_version") != expected_compiler_version
                or manifest.get("ir_version") != IR_VERSION
                or manifest.get("playbook_version") != "capture-playbook-draft/v2"
            ):
                raise PlaybookError(
                    "[BUILD_VERSION_UNSUPPORTED] incompatible build manifest/backend"
                )
            runtime_identity = manifest.get("runtime_identity")
            if (
                not isinstance(runtime_identity, dict)
                or runtime_identity.get("package") != RUNTIME_PACKAGE
                or runtime_identity.get("version")
                not in SUPPORTED_RUNTIME_PACKAGE_VERSIONS
            ):
                raise PlaybookError(
                    "[BUILD_RUNTIME_UNSUPPORTED] incompatible runtime identity"
                )
        verified = verify_bot_build(
            directory,
            hashlib.sha256(manifest_bytes).hexdigest(),
            supported_versions=("bot-build-manifest/v1", "bot-build-manifest/v2"),
        )
    except (OSError, json.JSONDecodeError, BotBuildVerificationError) as error:
        raise PlaybookError(str(error)) from error
    manifest = verified.manifest
    if (
        manifest.get("backend_id") != expected_backend_id
        or manifest.get("backend_version") != expected_backend_version
        or manifest.get("compiler_version") != expected_compiler_version
        or manifest.get("ir_version") != IR_VERSION
        or manifest.get("playbook_version") != "capture-playbook-draft/v2"
    ):
        raise PlaybookError(
            "[BUILD_VERSION_UNSUPPORTED] incompatible build manifest/backend"
        )
    expected_profile = hashlib.sha256(canonical_json(profile)).hexdigest()
    if manifest.get("capability_profile_sha256") != expected_profile:
        raise PlaybookError(
            "[BUILD_PROFILE_UNSUPPORTED] backend capability profile differs"
        )
    if manifest.get("manifest_version") == "bot-build-manifest/v2":
        expected_profile_id = {
            "python-http-reference": "python-http-reference-v1",
            "scrapy-fixture": "scrapy-fixture-v1",
            "scrapy-live-http": "scrapy-live-http-v1",
        }.get(expected_backend_id)
        if manifest.get("capability_profile_id") != expected_profile_id:
            raise PlaybookError("[BUILD_PROFILE_UNSUPPORTED] profile identity differs")
    lock_digest = (
        manifest.get("dependency_identity", {}).get("lockfile_sha256")
        if manifest.get("manifest_version") == "bot-build-manifest/v2"
        else manifest.get("dependency_lock_sha256")
    )
    lockfile = Path(__file__).resolve().parents[3] / "uv.lock"
    if (
        not lockfile.is_file()
        or hashlib.sha256(lockfile.read_bytes()).hexdigest() != lock_digest
    ):
        raise PlaybookError(
            "[BUILD_DEPENDENCIES_UNSUPPORTED] dependency lock digest differs"
        )
    toolchain = manifest.get("toolchain")
    if not isinstance(toolchain, dict):
        raise PlaybookError("[BUILD_MANIFEST_INVALID] toolchain must be an object")
    required_toolchain = expected_toolchain or {
        "python": platform.python_version(),
        "python_implementation": platform.python_implementation(),
        "platform_system": platform.system(),
        "platform_machine": platform.machine(),
        "runtime": RUNTIME_VERSION,
        "selectolax": "0.4.13",
    }
    if any(toolchain.get(key) != value for key, value in required_toolchain.items()):
        raise PlaybookError(
            "[BUILD_TOOLCHAIN_UNSUPPORTED] build toolchain identity differs"
        )
    if manifest.get("manifest_version") == "bot-build-manifest/v2":
        compatibility = manifest["compatibility"]
        if (
            compatibility.get("python_minor")
            != f"{platform.python_version_tuple()[0]}.{platform.python_version_tuple()[1]}"
        ):
            raise PlaybookError("[BUILD_TOOLCHAIN_UNSUPPORTED] Python minor differs")
        if manifest.get("playbook_sha256") is not None and (
            not isinstance(manifest["playbook_sha256"], str)
            or len(manifest["playbook_sha256"]) != 64
            or any(
                char not in "0123456789abcdef" for char in manifest["playbook_sha256"]
            )
        ):
            raise PlaybookError("[PLAYBOOK_DIGEST_INVALID] manifest digest is invalid")
    return manifest
